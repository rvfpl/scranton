            <h2 class="heading--secondary">Pytania klientów</h2>
                            <div class="course__questions scrollable row">
                                            <div class="col col-md-6">
                            <div class="question">
    <h2 class="question__content">Dla kogo jest ten kurs?</h2>
    <p class="question__answer">Motywacje do nauki wśród naszych kursantów w Gliwicach są bardzo różne. W kursach biorą udział <strong>pasjonaci kultury</strong> Japonii, <strong>mangi</strong> i <strong>anime</strong> oraz azjatyckiej muzyki, a także osoby planujące <strong>wyjechać do Japonii</strong> na wakacje lub do pracy. Niektórzy chcą przygotować się do rozpoczęcia studiów na <strong>japonistyce</strong>. Niezależnie od motywacji dopasujemy kurs japońskiego do Twoich potrzeb.</p>
</div>                        </div>
                                            <div class="col col-md-6">
                            <div class="question">
    <h2 class="question__content">Kto będzie moim nauczycielem?</h2>
    <p class="question__answer">Naukę japońskiego <strong>od podstaw</strong> rozpoczynamy z&nbsp;<strong>polskim lektorem</strong>, który łatwiej wytłumaczy gramatykę<strong> </strong>i nowe struktury językowe. Na wyższych poziomach<strong> </strong>wprowadzamy konwersacje z&nbsp;<strong>native speakerem. </strong>Nasi lektorzy są absolwentami <strong>filologii japońskiej</strong> lub posiadają certyfikat <strong>JLPT.</strong></p>
</div>                        </div>
                                            <div class="col col-md-6">
                            <div class="question">
    <h2 class="question__content">Jakie materiały otrzymam w ramach kursu?</h2>
    <p class="question__answer">Na kursach grupowych&nbsp;w Gliwicach każdy otrzymuje zestaw książek <strong>Minna no Nihongo</strong>, który sprowadzamy dla Was z&nbsp;Japonii<strong>.</strong> Książki te używane są <strong>na wielu uczelniach</strong> na kierunku japonistyka. Dodatkowe materiały, również są wliczone w cenę zajęć. Kursantom indywidualnym oferujemy zakup podręcznika w preferencyjnej cenie.</p>
</div>                        </div>
                                            <div class="col col-md-6">
                            <div class="question">
    <h2 class="question__content">Od czego zaczynamy naukę na kursach dla początkujących?</h2>
    <p class="question__answer">Kurs japońskiego dla początkujących zaczynamy od&nbsp;<strong>nauki&nbsp;hiragany&nbsp;i&nbsp;katakany</strong> oraz podstawowego słownictwa i zwrotów, używanych na co dzień w Japonii. Następnie wprowadzamy <strong>znaki kanji</strong> i doskonalimy czytanie po japońsku. Gdy poznamy alfabet<strong> </strong>rozpoczynamy pracę z podręcznikiem <strong>Minna no Nihongo</strong>, uczymy podstaw <strong>gramatyki</strong>, ćwiczymy proste dialogi oraz słuchanie w języku japońskim<strong>.</strong></p>
</div>                        </div>
                                            <div class="col col-md-6">
                            <div class="question">
    <h2 class="question__content">Co jeśli uczę się języka japońskiego samemu lub w innej szkole?</h2>
    <p class="question__answer">W<strong> Gliwicach </strong>mamy grupy zarówno podstawowe, jak i średnio-zaawansowane, do których możesz dołączyć <strong>przez cały rok</strong>. Po zapisie na kurs przeprowadzimy <strong>test poziomujący</strong>, a następnie zaproponujemy bezpłatnie <strong>zajęcia próbne</strong>. Jeżeli grupa będzie odpowiednia możesz podpisać umowę.</p>
</div>                        </div>
                                            <div class="col col-md-6">
                            <div class="question">
    <h2 class="question__content">Kiedy rozpoczynają się kursy grupowe języka japońskiego?</h2>
    <p class="question__answer">Kursy grupowe rozpoczynają się we <strong>wrześniu</strong> oraz w <strong>lutym</strong>. W lipcu startują intensywne kursy wakacyjne <strong>od podstaw</strong>. W praktyce uruchamiamy nowe kursy <strong>przez cały rok</strong>, gdy tylko zbierzemy grupę. Można również dołączyć do kursów, które już się rozpoczęły, pomagamy wtedy indywidualnie nadrobić materiał.</p>
</div>                        </div>
                                            <div class="col col-md-6">
                            <div class="question">
    <h2 class="question__content">Czy mogę kontynuować kurs w następnym semestrze?</h2>
    <p class="question__answer"><strong>Tak</strong>, wszyscy kursanci, którzy uczestniczą w kursie języka japońskiego, dostają <strong>propozycję kontynuacji</strong> kursu w kolejnym roku szkolnym na <strong>wyższym poziomie</strong>. Niektórzy kursanci w Gliwicach są z nami już kilka lat.</p>
</div>                        </div>
                                            <div class="col col-md-6">
                            <div class="question">
    <h2 class="question__content">Czy prowadzimy kursy dla dzieci?</h2>
    <p class="question__answer"><strong>Tak</strong>, prowadzimy naukę języka japońskiego w Gliwicach <strong>dla dzieci.</strong> Dla młodszych kursantów często proponujemy zajęcia <strong>skrócone </strong>aby nauka była jak najbardziej efektywna. Metody nauczania są dostosowane do wieku uczestników, a poza lekcjami organizujemy <strong>wydarzenia </strong>skierowane do dzieci, dzięki którym mogą poznawać <strong>kulturę azjatycką</strong>.</p>
</div>                        </div>
                                            <div class="col col-md-6">
                            <div class="question">
    <h2 class="question__content">Czy język japoński jest trudny?</h2>
    <p class="question__answer">Podstawy japońskiego, czyli między innymi <strong>alfabet japoński</strong> (znaki<strong> hiragany i katakany</strong>), nie są trudne do opanowania. <strong>Gramatyka </strong>japońska różni się od tej znanej z języków europejskich, a nauka <strong>znaków kanji </strong>wymaga systematyczności. Szczególnie na początku nauki warto skorzystać z pomocy <strong>doświadczonego lektora</strong>.</p>
</div>                        </div>
                                            <div class="col col-md-6">
                            <div class="question">
    <h2 class="question__content">Czy kursy przygotowują do egzaminu JLPT?</h2>
    <p class="question__answer">Wymagania do egzaminu JLPT <strong>pokrywają się z programem kursu</strong> języka japońskiego. Jeżeli Twoją motywacją jest zdanie egzaminu nasi lektorzy przygotują Cię<strong> do każdego poziomu</strong>. Certyfikat JLPT jest ceniony w pracy zarówno w Polsce jak i w Japonii, dlatego warto spróbować.</p>
